export function getDemoMatchStatsBundle(
  matchId: string,
  status: string | undefined
): DemoMatchStatsBundle {
  if (status === "scheduled" || status === "rainout") {
    return {
      stats: [],
      pitcherStats: [],
      gameDetails: EMPTY_GAME_DETAILS,
      playLogs: [],
    };
  }
  if (matchId === "demo-match-2") {
    return DEMO_MATCH_2_BUNDLE;
  }
  if (matchId === "demo-match-1" || matchId === "sample-match") {
    return DEMO_MATCH_1_BUNDLE;
  }
  return {
    stats: [],
    pitcherStats: [],
    gameDetails: EMPTY_GAME_DETAILS,
    playLogs: [],
  };
}

